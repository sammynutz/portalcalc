"""Generate the engine's input-field schema from the real input form.

``portalcalc/frame/engine/form_schema.json`` lists every input and result field
the desktop form creates, with its starting value and (for drop-downs) its
options. ``HeadlessFrameEngine`` builds its plain fields from that file, so the
engine can run with no window and still start from exactly the same state.

Regenerate after changing the form (``ui_build.py``) or the section catalogue:

    python -m portalcalc.desktop.form_schema

``tests/headless_engine_regression.py`` fails when the file is out of date.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

SCHEMA_PATH = Path(__file__).resolve().parents[1] / "frame" / "engine" / "form_schema.json"
# Text that depends on the machine it was generated on, not on the form.
MACHINE_DEPENDENT = {"license_status_label", "factory_defaults_status_label"}


def _plain(value):
    try:
        json.dumps(value)
    except (TypeError, ValueError):
        return False
    return True


def build_schema() -> dict:
    """Open the form offscreen and describe its fields as they are when the form is first built."""
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    from PySide6.QtCore import QObject
    from PySide6.QtWidgets import (QApplication, QCheckBox, QComboBox, QDoubleSpinBox, QLabel, QLineEdit,
                                   QPushButton, QRadioButton, QSpinBox, QTextEdit, QToolButton)

    from portalcalc.desktop.main_window import MainWindow
    from portalcalc.desktop.widgets import BuildingEnvelopeSelector, CompassSelector, LeanToEnvelopeProxy

    app = QApplication.instance() or QApplication([])  # noqa: F841 (kept alive for the window)
    captured = {}

    class Probe(MainWindow):
        def build_ui(self):
            before = set(vars(self))
            super().build_ui()
            captured.update({name: value for name, value in vars(self).items() if name not in before})

    window = Probe()
    window.confirm_on_close = False
    item_lists: dict[str, list] = {}
    list_ids: dict[str, str] = {}

    def items_id(combo):
        items = [[combo.itemText(i), combo.itemData(i)] for i in range(combo.count())]
        key = json.dumps(items, sort_keys=True)
        if key not in list_ids:
            list_ids[key] = f"options_{len(list_ids) + 1}"
            item_lists[list_ids[key]] = items
        return list_ids[key]

    def describe(name, widget):
        if isinstance(widget, QComboBox):
            return {"kind": "choice", "items": items_id(widget), "index": widget.currentIndex()}
        if isinstance(widget, (QCheckBox, QRadioButton)):
            return {"kind": "check", "checked": widget.isChecked()}
        if isinstance(widget, QDoubleSpinBox):
            return {"kind": "number", "value": widget.value(), "minimum": widget.minimum(),
                    "maximum": widget.maximum(), "decimals": widget.decimals()}
        if isinstance(widget, QSpinBox):
            return {"kind": "number", "value": widget.value(), "minimum": widget.minimum(), "maximum": widget.maximum()}
        if isinstance(widget, QTextEdit):
            return {"kind": "text", "text": widget.toPlainText()}
        if isinstance(widget, (QLineEdit, QLabel, QPushButton, QToolButton)):
            return {"kind": "text", "text": "" if name in MACHINE_DEPENDENT else widget.text()}
        if isinstance(widget, CompassSelector):
            return {"kind": "orientation", "text": widget.currentText()}
        if isinstance(widget, BuildingEnvelopeSelector):
            return {"kind": "envelope", "main": widget.main_selector.wall_states(),
                    "left": widget.left_selector.wall_states(), "right": widget.right_selector.wall_states()}
        return None

    fields, state, first_name = {}, {}, {}
    envelope_names = {id(value): name for name, value in captured.items() if isinstance(value, BuildingEnvelopeSelector)}
    for name in sorted(captured):
        value = captured[name]
        if isinstance(value, LeanToEnvelopeProxy):
            fields[name] = {"kind": "lean_to_envelope", "of": envelope_names[id(value.selector)], "side": value.side}
        elif isinstance(value, QObject):
            if id(value) in first_name:
                fields[name] = {"same_as": first_name[id(value)]}
                continue
            spec = describe(name, value)
            if spec is not None:
                fields[name] = spec
                first_name[id(value)] = name
        elif not name.startswith("__") and not name.endswith("_rows") and _plain(value):
            state[name] = value
    window.close()
    return {
        "about": "Generated by `python -m portalcalc.desktop.form_schema`; do not edit by hand.",
        "fields": fields,
        "option_lists": item_lists,
        "state": state,
    }


def write_schema() -> Path:
    schema = build_schema()
    SCHEMA_PATH.write_text(json.dumps(schema, indent=1, sort_keys=True) + "\n", encoding="utf-8")
    return SCHEMA_PATH


if __name__ == "__main__":
    os.environ["PORTALCALC_LICENSE_ENFORCED"] = "0"
    path = write_schema()
    data = json.loads(path.read_text(encoding="utf-8"))
    print(f"Wrote {path} ({path.stat().st_size / 1024:.0f} KB): {len(data['fields'])} fields, "
          f"{len(data['option_lists'])} option lists")
